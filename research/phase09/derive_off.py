"""Deterministic, inspectable source erasure; never modifies frozen ancestors.

This is a transformation of these particular reviewed sources, not a general
instrumentation-removal compiler. --check compares the generated artifact.
"""
import argparse
import ast
from copy import deepcopy
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


class Erase(ast.NodeTransformer):
    def __init__(self, source, fresh=False):
        self.source, self.fresh = source, fresh
        self.removed = []

    def drop(self, node, reason):
        self.removed.append({"line": node.lineno, "reason": reason,
                             "source": ast.get_source_segment(self.source, node)})
        return None

    def dead_target(self, target):
        if isinstance(target, ast.Name):
            return target.id in ("cost", "start") or (self.fresh and target.id == "size")
        if isinstance(target, ast.Subscript):
            return isinstance(target.value, ast.Name) and target.value.id == "cost"
        return (isinstance(target, ast.Attribute) and isinstance(target.value, ast.Name)
                and target.value.id == "self" and target.attr in ("peak_bytes", "peak_entries"))

    def visit_Assign(self, node):
        kept = [t for t in node.targets if not self.dead_target(t)]
        if not kept:
            return self.drop(node, "reporting_assignment_or_fresh_source_size")
        if len(kept) != len(node.targets):
            self.removed.append({"line": node.lineno, "reason": "remove_peak_targets_only",
                                 "source": ast.get_source_segment(self.source, node)})
            node.targets = kept
        return self.generic_visit(node)

    def visit_AugAssign(self, node):
        return self.drop(node, "reporting_counter") if self.dead_target(node.target) else self.generic_visit(node)

    def visit_Expr(self, node):
        if isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name) and node.value.func.id == "action":
            return self.drop(node, "reporting_control_event")
        return self.generic_visit(node)

    def visit_FunctionDef(self, node):
        node.args.args = [a for a in node.args.args if a.arg != "cost"]
        node = self.generic_visit(node)
        if not node.body:
            node.body = [ast.Pass()]
        return node

    def visit_If(self, node):
        node = self.generic_visit(node)
        if not node.body:
            node.body = [ast.Pass()]
        return node

    def visit_Call(self, node):
        if isinstance(node.func, ast.Name) and node.func.id == "finish":
            return self.visit(node.args[0])
        if (isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "P6" and node.func.attr == "validate"):
            node.func = ast.Name(id="validate", ctx=ast.Load())
        if isinstance(node.func, ast.Name) and node.func.id == "counted_digest":
            node.func.id = "digest"
        node.args = [a for a in node.args if not (isinstance(a, ast.Name) and a.id == "cost")]
        return self.generic_visit(node)


def generate():
    p8 = ROOT / "research/phase08/runtime.py"
    p6 = ROOT / "research/phase06/scoped.py"
    sources = {"phase08": p8.read_text(), "phase06": p6.read_text()}
    trees = {name: ast.parse(src) for name, src in sources.items()}
    def get(which, name):
        return deepcopy(next(x for x in trees[which].body if isinstance(x, (ast.FunctionDef, ast.ClassDef)) and x.name == name))
    header = '''"""Conservative telemetry erasure of frozen P6/P8, generated by derive_off.py.

Policy, data structures and branch order are retained. No counters, event log,
internal timers, peak statistics or P7/P8 reporting. Source-size UTF8 in fresh
is dead and erased; selective raw UTF8 is retained as a shared key/L operand.
Rendering and its original UTF8 encoding remain. Supported research entry:
run_fresh(public) with default text_scoped; run_selective(public, cache).
"""
from collections import Counter
from collections.abc import Mapping
from functools import cmp_to_key
from types import MappingProxyType
import hashlib
import json
from bindings import P6, SEMANTIC_FINGERPRINT
BASE = P6.BASE
METHODS = P6.METHODS
scope_from_text = P6.scope_from_text
scoped_top = P6.scoped_top
writes = P6.writes
preimage = P6.preimage
execute = P6.execute
render = P6.render
frozen = P6.frozen  # Non-default legacy entry is outside the erasure contract.
'''
    nodes = ast.parse(header).body
    for node in trees["phase08"].body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in (
                "STAGES", "MIN_CHARS", "META_BYTES", "ACTION_WEIGHT", "WARM_ACTIONS")
                or isinstance(t, ast.Tuple) for t in node.targets):
            nodes.append(deepcopy(node))
    for name in ("plain", "encode", "immutable"):
        nodes.append(get("phase08", name))
    eraser8 = Erase(sources["phase08"])
    nodes.append(eraser8.visit(get("phase08", "SelectiveCache")))
    eraser6 = Erase(sources["phase06"], fresh=True)
    d = get("phase06", "counted_digest")
    d.name = "digest"
    nodes.append(eraser6.visit(d))
    nodes.append(eraser6.visit(get("phase06", "validate")))
    fresh = get("phase06", "run")
    fresh.name = "run_fresh"
    nodes.append(eraser6.visit(fresh))
    selective = get("phase08", "run")
    selective.name = "run_selective"
    nodes.append(eraser8.visit(selective))
    tree = ast.fix_missing_locations(ast.Module(body=nodes, type_ignores=[]))
    output = ast.unparse(tree) + "\n"
    # No cost read, event call, timer or peak state may survive.
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            assert node.id not in {"cost", "action", "perf_counter", "start"}, ast.dump(node)
        if isinstance(node, ast.Attribute):
            assert node.attr not in {"peak_bytes", "peak_entries"}
    manifest = {"source_sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in (p6, p8)},
                "policy": "conservative source-level erasure; no path-sensitive lazy encoding or data-structure optimization",
                "phase06_removed": eraser6.removed, "phase08_removed": eraser8.removed,
                "generated_sha256": hashlib.sha256(output.encode()).hexdigest()}
    return output, json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    runtime, manifest = generate()
    for name, value in (("runtime_off.py", runtime), ("ERASURE_MAP.json", manifest)):
        path = HERE / name
        if args.check:
            assert path.read_text() == value, name
        else:
            path.write_text(value)
    print("Generated erasure matches sources." if args.check else "Generated off runtime and erasure map.")
